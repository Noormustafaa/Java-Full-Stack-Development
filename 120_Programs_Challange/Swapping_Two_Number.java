
package pkg120_programs_in_java;


public class Swapping_Two_Number {

   
    public static void main(String[] args) {
        
        
        
       //Logic 1 Using Third Variable 
       
       int a=20;
       int b=30;
       
        System.out.println("Before_Swapping value of a:"+a+" and   b:"+ b );
       
       int t=20;
       
       a=b; //so here a=30 now
       b=t; // and now b= here 20
    
     System.out.println("After_Swapping value of a:"+a+" and   b:"+ b );
       
    }
    
}
